/* Part of the headless render harness -- see tools/render/README.md.
   Zero dependencies, Node built-ins only, so the repo stays dependency-free.
   --------------------------------------------------------------
   bake-board.mjs -- the prep-board frames in, content/board/ out.

       node tools/render/bake-board.mjs [dir]

   dir defaults to reference/kitchen/board-frames/: one transparent 40x38 PNG
   per build state in states/, named by recipe prefix (LARGE-BEANS-CHEESE.png),
   plus manifest.json, which gives every dish its recipe and its finished frame.

   Writes one table per frame to content/board/<key>.json -- the same 16-colour
   run-length format as the faces and wells, so Faces.decode reads it -- and
   content/board.json, the finish map: the dishes whose finished picture is not
   simply their last build frame (a rolled burrito, a folded soft taco).

   Same round-trip guard as bake-lattice.mjs: every table is decoded with the
   shipped decoder and compared pixel for pixel before it is kept. The frames
   are authored AT board size, so there is no crop and no scaling here, only
   the colour reduction. Re-run it whenever the art director's set changes;
   it clears out content/board/ first so a dropped frame cannot linger. */
import { readPNG } from './png-read.mjs';
import { medianCut, snap, hex } from './reduce.mjs';
import { decodeFace, L64 } from '../../reference/kitchen/facedata.mjs';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = process.argv[2] || join(ROOT, 'reference', 'kitchen', 'board-frames');
const OUT_DIR = join(ROOT, 'content', 'board');
const FINISH = join(ROOT, 'content', 'board.json');
const W = 40, H = 38, INK = '#1b1425';

const man = JSON.parse(readFileSync(join(SRC, 'manifest.json'), 'utf8'));

/* Every frame any dish uses, so a stray PNG in states/ is not baked and a
   missing one fails here rather than in the build. */
const keys = new Set();
const finish = {};
for (const [dish, r] of Object.entries(man.recipes)) {
  for (const k of r.build) keys.add(k);
  keys.add(r.wrapped);
  if (r.wrapped !== r.build[r.build.length - 1]) finish[dish.toUpperCase()] = r.wrapped;
}

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

let total = 0;
for (const key of [...keys].sort()) {
  const img = readPNG(join(SRC, 'states', key + '.png'));
  if (img.width !== W || img.height !== H)
    throw new Error(`${key}.png is ${img.width}x${img.height}; the board frame is ${W}x${H}`);
  /* Hard-edged alpha first: a half-transparent edge pixel would otherwise
     pull the palette toward the background it was anti-aliased against. */
  for (let i = 0; i < img.data.length; i += 4) img.data[i + 3] = img.data[i + 3] > 127 ? 255 : 0;
  const cv = snap(img, medianCut(img, 16));

  const seen = new Map();
  for (let k = 0; k < cv.data.length; k += 4) {
    if (!cv.data[k + 3]) continue;
    const c = hex([cv.data[k], cv.data[k + 1], cv.data[k + 2]]);
    seen.set(c, (seen.get(c) || 0) + 1);
  }
  const pal = [...seen.entries()].sort((a, b) => b[1] - a[1]).map(([c]) => c);
  if (pal.length > 16) throw new Error(`${key}: ${pal.length} colours, 16 is the cap`);
  const idx = new Map(pal.map((c, n) => [c, n]));

  let pix = '';
  for (let y = 0; y < H; y++) {
    let sym = null, len = 0;
    const flush = () => { while (len > 0) { const n = Math.min(len, 63); pix += sym + L64[n]; len -= n; } };
    for (let x = 0; x < W; x++) {
      const k = (y * W + x) * 4;
      const s = cv.data[k + 3] ? idx.get(hex([cv.data[k], cv.data[k + 1], cv.data[k + 2]])).toString(16) : '.';
      if (s === sym) len++; else { flush(); sym = s; len = 1; }
    }
    flush();
  }

  const rec = { name: key, w: W, h: H, ink: INK, skin: pal[0], eyes: [], pal, pix };
  const back = decodeFace(rec);
  let bad = 0;
  for (let k = 0; k < cv.data.length; k += 4) {
    const a = cv.data[k + 3] ? [cv.data[k], cv.data[k + 1], cv.data[k + 2]] : null;
    const b = back.data[k + 3] ? [back.data[k], back.data[k + 1], back.data[k + 2]] : null;
    if (!a !== !b || (a && (a[0] !== b[0] || a[1] !== b[1] || a[2] !== b[2]))) bad++;
  }
  if (bad) throw new Error(`${key}: round trip differs in ${bad}px`);

  const json = JSON.stringify(rec) + '\n';
  writeFileSync(join(OUT_DIR, key.toLowerCase() + '.json'), json);
  total += json.length;
}

writeFileSync(FINISH, JSON.stringify({
  _note: 'Generated by tools/render/bake-board.mjs. The dishes whose finished picture on the prep board is not their last build frame. Every other dish finishes on its last build frame.',
  finish,
}, null, 2) + '\n');

console.log(`${keys.size} frames -> content/board/  (${(total / 1024).toFixed(1)} KB of tables)`);
console.log(`${Object.keys(finish).length} separate finishes -> content/board.json`);
