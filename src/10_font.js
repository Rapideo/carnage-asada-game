const FW = 5, FH = 7;
const GLYPH = Object.create(null);
for (const ch in FONT_SRC) {
  const rows = FONT_SRC[ch].split(',');
  const bits = [];
  for (let y = 0; y < FH; y++) {
    const r = rows[y] || '00000';
    for (let x = 0; x < FW; x++) if (r[x] === '1') bits.push(x, y);
  }
  GLYPH[ch] = bits;
}

/** width of a string in px at a given scale (1px letter gap) */
function textW(str, s = 1) { return str.length ? (str.length * (FW + 1) - 1) * s : 0; }

/**
 * Draw pixel text. `align`: 0=left 1=center 2=right.
 */
function text(x, str, px, py, col, s = 1, align = 0, shadow = null) {
  str = String(str).toUpperCase();
  let ox = px | 0;
  if (align === 1) ox = (px - textW(str, s) / 2) | 0;
  else if (align === 2) ox = (px - textW(str, s)) | 0;
  const oy = py | 0;

  if (shadow) drawRun(x, str, ox + s, oy + s, shadow, s);
  drawRun(x, str, ox, oy, col, s);
  return ox;
}

function drawRun(x, str, ox, oy, col, s) {
  x.fillStyle = col;
  let cx = ox;
  for (let i = 0; i < str.length; i++) {
    const g = GLYPH[str[i]];
    if (g) for (let b = 0; b < g.length; b += 2) x.fillRect(cx + g[b] * s, oy + g[b + 1] * s, s, s);
    cx += (FW + 1) * s;
  }
}

/** text with a 1px outline in every direction — for HUD over busy ground */
function textOut(x, str, px, py, col, s = 1, align = 0, oc = PAL.ink) {
  str = String(str).toUpperCase();
  let ox = px | 0;
  if (align === 1) ox = (px - textW(str, s) / 2) | 0;
  else if (align === 2) ox = (px - textW(str, s)) | 0;
  for (let dy = -s; dy <= s; dy += s)
    for (let dx = -s; dx <= s; dx += s)
      if (dx || dy) drawRun(x, str, ox + dx, py + dy, oc, s);
  drawRun(x, str, ox, py, col, s);
  return ox;
}

/** money formatter: 1234 cents -> "$12.34" */
function money(cents) {
  const neg = cents < 0; cents = Math.abs(Math.round(cents));
  const s = '$' + ((cents / 100) | 0) + '.' + String(cents % 100).padStart(2, '0');
  return neg ? '-' + s : s;
}
function clockStr(sec) {
  sec = Math.max(0, sec);
  const m = (sec / 60) | 0, s = (sec % 60) | 0;
  return m + ':' + String(s).padStart(2, '0');
}
